"""
compare_results.py - compare the result files regenerated by run_all.py with the archived ones.

Usage (from any folder; paths may be absolute):
  python Codes/compare_results.py --ref path/to/untouched/copy/of/the/archive     (folder with results/ and data/)
  python Codes/compare_results.py --ref archive_code_and_data.zip --ref archive_large_files.zip
  python Codes/compare_results.py --ref ... --root path/to/regenerated/project   (default: this project folder)

Every file under results/ and data/derived/ of the reference is compared with the same file in the regenerated
project (CSV, CSV.GZ, JSON, NPY and NPZ by value; other files byte by byte). Status of each file:
  identical         byte-identical to the archived file
  equal             same shape, labels and text; every number within |a - b| <= atol + rtol * |b|
  DIFFERENT         values differ beyond the tolerance (number of differing values and largest difference listed)
  not regenerated   older than the start of the run (logs/run_all_started.txt), so this run did not rewrite it
                    and the comparison would not be informative (e.g. files written only at packaging)
  missing           in the reference but not in this folder
Seeds are fixed, so 'identical' or 'equal' is expected for every regenerated file. Tiny floating-point differences
(another CPU, operating system or BLAS build) fall within the tolerance. P values are discrete, so a changed P value
is always reported. A report is written to logs/compare_results_report.csv.
Exit status: 0 if no file is DIFFERENT or missing, 1 otherwise.
"""
import argparse
import io
import json
import os
import sys
import zipfile
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(os.environ.get("HEMIHOM_ROOT", Path(__file__).resolve().parents[1]))
SUBDIRS = ("results/", "data/derived/")


def reference_files(refs):
    """Map 'results/...' and 'data/derived/...' paths to a function returning the reference bytes."""
    out = {}
    for ref in refs:
        ref = Path(ref).expanduser().resolve()
        if ref.is_file() and zipfile.is_zipfile(ref):
            z = zipfile.ZipFile(ref)
            for name in z.namelist():
                if name.endswith("/"):
                    continue
                rel = name.split("/", 1)[1] if "/" in name else name   # drop the top folder (spatialcv_v3/)
                if rel.startswith(SUBDIRS):
                    out[rel] = (lambda z=z, name=name: z.read(name))
        elif ref.is_dir():
            for sub in SUBDIRS:
                for p in sorted((ref / sub).rglob("*")):
                    if p.is_file():
                        out[str(p.relative_to(ref)).replace("\\", "/")] = (lambda p=p: p.read_bytes())
        else:
            sys.exit(f"reference not found or not a zip file/folder: {ref}")
    return out


def close(a, b, rtol, atol):
    a, b = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    ok = np.isclose(a, b, rtol=rtol, atol=atol, equal_nan=True)
    d = np.abs(a - b)
    d = d[~(np.isnan(a) & np.isnan(b))]
    return int((~ok).sum()), int(ok.size), (float(np.nanmax(d)) if d.size else 0.0)


def numeric(s):
    """A pandas column as floats if all its non-missing values are numbers, otherwise None."""
    if pd.api.types.is_bool_dtype(s) or pd.api.types.is_numeric_dtype(s):
        return s.astype(float).to_numpy()
    v = pd.to_numeric(s, errors="coerce")
    return v.to_numpy(float) if v.notna().sum() == s.notna().sum() else None


def compare_frames(a, b, rtol, atol):
    if list(a.columns) != list(b.columns):
        return None, 0, 0.0, "different columns"
    if a.shape != b.shape:
        return None, 0, 0.0, f"different shape {a.shape} vs {b.shape}"
    res = _compare_aligned(a, b, rtol, atol)
    if res[0]:   # same rows in another order (e.g. parts merged in another order)?
        keys = [c for c in a.columns if numeric(a[c]) is None] or list(a.columns)
        a2 = a.sort_values(keys, kind="stable").reset_index(drop=True)
        b2 = b.sort_values(keys, kind="stable").reset_index(drop=True)
        res2 = _compare_aligned(a2, b2, rtol, atol)
        if res2[0] == 0:
            return 0, res2[1], 0.0, "rows in a different order"
    return res


def _compare_aligned(a, b, rtol, atol):
    ndiff, n, dmax, worst = 0, 0, 0.0, ""
    for c in a.columns:
        x, y = numeric(a[c]), numeric(b[c])
        if x is not None and y is not None:
            k, m, d = close(x, y, rtol, atol)
        else:
            sa = a[c].fillna("").astype(str).to_numpy(dtype=object)   # missing == missing (pandas 3 keeps NA in str)
            sb = b[c].fillna("").astype(str).to_numpy(dtype=object)
            k, m, d = int((sa != sb).sum()), len(sa), (np.inf if (sa != sb).any() else 0.0)
        ndiff, n = ndiff + k, n + m
        if k and d >= dmax:
            dmax, worst = d, c
    return ndiff, n, dmax, (f"column '{worst}'" if ndiff else "")


def compare_json(a, b, rtol, atol, path="$"):
    """Returns (number of differing leaves, number of leaves, largest numeric difference, first differing path)."""
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            return 1, 1, np.inf, f"{path}: different keys"
        res = [compare_json(a[k], b[k], rtol, atol, f"{path}.{k}") for k in a]
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return 1, 1, np.inf, f"{path}: different lengths"
        res = [compare_json(x, y, rtol, atol, f"{path}[{i}]") for i, (x, y) in enumerate(zip(a, b))]
    elif isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        k, _, d = close(a, b, rtol, atol)
        return k, 1, d, (path if k else "")
    else:
        return int(a != b), 1, (np.inf if a != b else 0.0), (path if a != b else "")
    nd = sum(r[0] for r in res)
    first = next((r[3] for r in res if r[0]), "")
    return nd, sum(r[1] for r in res), max([r[2] for r in res] or [0.0]), first


def compare(rel, ref_bytes, new_path, rtol, atol):
    new_bytes = new_path.read_bytes()
    if new_bytes == ref_bytes:
        return "identical", 0, None, 0.0, ""
    name = rel.lower()
    try:
        if name.endswith((".csv", ".csv.gz")):
            comp = "gzip" if name.endswith(".gz") else None
            a = pd.read_csv(io.BytesIO(new_bytes), compression=comp, low_memory=False)
            b = pd.read_csv(io.BytesIO(ref_bytes), compression=comp, low_memory=False)
            nd, n, d, info = compare_frames(a, b, rtol, atol)
        elif name.endswith(".json"):
            nd, n, d, info = compare_json(json.loads(new_bytes), json.loads(ref_bytes), rtol, atol)
        elif name.endswith((".npy", ".npz")):
            a, b = np.load(io.BytesIO(new_bytes), allow_pickle=False), np.load(io.BytesIO(ref_bytes), allow_pickle=False)
            pairs = [(k, a[k], b[k]) for k in b.files] if name.endswith(".npz") else [("array", a, b)]
            if name.endswith(".npz") and set(a.files) != set(b.files):
                return "DIFFERENT", 1, 1, np.inf, "different arrays in the archive"
            nd, n, d, info = 0, 0, 0.0, ""
            for k, x, y in pairs:
                if x.shape != y.shape:
                    return "DIFFERENT", 1, 1, np.inf, f"{k}: different shape {x.shape} vs {y.shape}"
                kk, m, dd = close(x, y, rtol, atol)
                nd, n = nd + kk, n + m
                if kk and dd >= d:
                    d, info = dd, f"array '{k}'"
        else:
            return "DIFFERENT", 1, 1, np.inf, "binary content differs"
    except Exception as e:  # unreadable or malformed file
        return "DIFFERENT", 1, 1, np.inf, f"could not be compared: {type(e).__name__}: {e}"
    if nd is None:
        return "DIFFERENT", 1, 1, np.inf, info
    return ("equal" if nd == 0 else "DIFFERENT"), nd, n, d, info


# Known platform sensitivity: random forests fitted to the simulated null maps of the pre-specified simulation B1.
# The simulated maps differ between platforms in the last bits (~1e-16, eigendecomposition in the map generator); the
# trees amplify this into small differences of individual R2 values (about 0.004 SD; observed maximum 0.015), while
# the false-positive rates derived from them are unchanged. Only these entries may be reported as "expected" instead of DIFFERENT.
KNOWN_NOTE = ("expected platform variation: random forests on simulated maps that differ in the last bits; "
              "false-positive rates unaffected")
def _rf_obs_ok(ref_bytes, new_path, res, rtol, atol):
    """Accept only if (i) all non-R2 columns agree, (ii) individual R2 values differ by < 0.02 and the per-scheme mean
    R2 by < 0.001, and (iii) the false-positive rate against the common shuffle null (Monte Carlo P < 0.05, as in the
    pre-specified analysis) is identical in every scheme."""
    a, b = pd.read_csv(io.BytesIO(ref_bytes)), pd.read_csv(new_path)
    if list(a.columns) != list(b.columns) or not a.drop(columns="r2").equals(b.drop(columns="r2")):
        return False
    if float(np.abs(a["r2"] - b["r2"]).max()) >= 0.02:
        return False
    nullf = Path(new_path).parent / "sim_B1_rf_shufnull.csv"
    if not nullf.exists():
        return False
    null = pd.read_csv(nullf)
    for s in sorted(a["scheme"].unique()):
        ns = null.loc[null["scheme"] == s, "r2"].to_numpy()
        ra, rb = a.loc[a["scheme"] == s, "r2"].to_numpy(), b.loc[b["scheme"] == s, "r2"].to_numpy()
        if abs(ra.mean() - rb.mean()) >= 1e-3:
            return False
        fpr = [np.mean([(1 + np.sum(ns >= o - 1e-12)) / (1 + ns.size) < 0.05 for o in r]) for r in (ra, rb)]
        if fpr[0] != fpr[1]:
            return False
    return True


def _rev_summary_ok(ref_bytes, new_path, res, rtol, atol):
    a, b = json.loads(ref_bytes), json.loads(Path(new_path).read_bytes())
    ra, rb = a.pop("rf_sim", {}), b.pop("rf_sim", {})
    if compare_json(a, b, rtol, atol)[0]:            # everything outside rf_sim must agree
        return False
    for s in ra:                                      # within rf_sim, the false-positive rates must agree
        for k in ("shuffle_fpr", "lo", "hi", "n"):
            if not np.isclose(ra[s][k], rb.get(s, {}).get(k, np.nan), rtol=rtol, atol=atol):
                return False
    return set(ra) == set(rb)


KNOWN = {"results/sim_B1_rf_obs.csv": _rf_obs_ok, "results/rev_summary.json": _rev_summary_ok}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", action="append", required=True,
                    help="archived reference: an untouched copy of the archive (folder) or its zip files "
                         "(repeat --ref for several)")
    ap.add_argument("--root", default=str(ROOT), help="folder with the regenerated files (default: this project)")
    ap.add_argument("--rtol", type=float, default=1e-6)
    ap.add_argument("--atol", type=float, default=1e-9)
    ap.add_argument("--since", default=None, help="start of the run (ISO time, UTC); default: logs/run_all_started.txt")
    ap.add_argument("--only-existing", action="store_true",
                    help="compare only the files that exist in --root (for partial reruns; missing files are skipped)")
    args = ap.parse_args()
    root = Path(args.root).expanduser().resolve()
    since = args.since
    stamp = root / "logs" / "run_all_started.txt"
    if since is None and stamp.exists():
        since = stamp.read_text(encoding="utf-8").strip()
    t0 = datetime.fromisoformat(since.replace("Z", "+00:00")).timestamp() if since else None
    if t0 is None:
        print("note: no logs/run_all_started.txt (run_all.py has not been run here); every file is compared")

    refs = reference_files(args.ref)
    if not refs:
        sys.exit("no results/ or data/derived/ files found in the reference")
    rows = []
    for rel in sorted(refs):
        new_path = root / rel
        if not new_path.exists():
            if not args.only_existing:
                rows.append((rel, "missing", None, None, None, ""))
        elif t0 is not None and new_path.stat().st_mtime < t0:
            rows.append((rel, "not regenerated", None, None, None, "older than the start of the run"))
        else:
            res = compare(rel, refs[rel](), new_path, args.rtol, args.atol)
            if res[0] == "DIFFERENT" and rel in KNOWN and KNOWN[rel](refs[rel](), new_path, res, args.rtol, args.atol):
                res = ("expected",) + tuple(res[1:4]) + (res[4] + "; " + KNOWN_NOTE,)
            rows.append((rel,) + res)
    rep = pd.DataFrame(rows, columns=["file", "status", "n_differing", "n_values", "max_abs_difference", "detail"])
    (root / "logs").mkdir(exist_ok=True)
    rep.to_csv(root / "logs" / "compare_results_report.csv", index=False)

    for _, r in rep[~rep["status"].isin(["identical", "equal"])].iterrows():
        if r.status in ("DIFFERENT", "expected") and r.n_values:
            size = (f"largest difference {r.max_abs_difference:.3g}" if np.isfinite(r.max_abs_difference)
                    else "text or structure differs")
            extra = f"{int(r.n_differing)} of {int(r.n_values)} values differ ({size}; {r.detail})"
        else:
            extra = r.detail if isinstance(r.detail, str) else ""
        print(f"{r.status:16s} {r.file}  {extra}".rstrip())
    counts = rep["status"].value_counts()
    print("\nSummary: " + ", ".join(f"{k} {counts.get(k, 0)}" for k in
                                   ["identical", "equal", "expected", "DIFFERENT", "not regenerated", "missing"]))
    print(f"Tolerance: |a - b| <= {args.atol:g} + {args.rtol:g} * |b|. Report: {root / 'logs' / 'compare_results_report.csv'}")
    bad = counts.get("DIFFERENT", 0) + counts.get("missing", 0)
    print("RESULT: all regenerated files agree with the archived results." if bad == 0 else
          "RESULT: some files differ or are missing; see the list above.")
    sys.exit(0 if bad == 0 else 1)


if __name__ == "__main__":
    main()
